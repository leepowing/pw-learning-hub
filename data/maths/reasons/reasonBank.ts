export type { ReasonId, ReasonUse } from './reasonTypes';
import type { ReasonId, ReasonOptions, ReasonUse } from './reasonTypes';

/** Explicit ID references embedded in existing string-based solution records.
 * No English/HKDSE label recognition takes place at runtime. */
export function reasonRef<I extends ReasonId>(reasonId: I, ...options: I extends `parallel.${string}` ? [ReasonOptions<I>] : [ReasonOptions<I>?]): string {
  return '⟦reason:' + JSON.stringify({ reasonId, ...(options[0] || {}) }) + '⟧';
}
export function reasonText(use: ReasonUse): {gcse: string; hkdse: string} {
  const entry = reasonBank[use.reasonId];
  if (!entry) throw new Error('Unknown geometry reason ID: ' + use.reasonId);
  const variants: Readonly<Record<string,string>> = entry.variants;
  if (use.variant && !variants[use.variant]) throw new Error('Unknown textbook variant: ' + use.reasonId + '/' + use.variant);
  const fill = (text: string) => text.replace(/\{(\w+)\}/g, (_, key: string) => {
    const params = use.params as Record<string,string> | undefined;
    if (!params?.[key]) throw new Error('Missing geometry reason parameter: ' + key);
    return params[key];
  });
  return {gcse: fill(entry.gcse), hkdse: fill(use.variant ? variants[use.variant] : entry.hkdse)};
}
